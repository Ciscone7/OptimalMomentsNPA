def _default_results_root() -> Path:
    """Default location for saved artifacts: spins_sdp/results."""
    return Path(__file__).resolve().parent / "spins_sdp" / "results"


def _iter_run_dirs(results_root: Path, artifact: str, schema_version: int) -> Iterable[Path]:
    """Iterate over run directories for a given artifact type."""
    base = results_root / artifact / f"v{schema_version}"
    if not base.exists():
        return []
    return [p for p in base.iterdir() if p.is_dir()]


def _load_meta(run_dir: Path) -> Dict[str, Any]:
    """Load meta.json from a run directory."""
    meta_path = run_dir / "meta.json"
    if not meta_path.exists():
        raise FileNotFoundError(f"Missing meta.json in {run_dir}")
    return json.loads(meta_path.read_text(encoding="utf-8"))


def _load_npz(run_dir: Path) -> Dict[str, np.ndarray]:
    """Load data.npz from a run directory."""
    data_path = run_dir / "data.npz"
    if not data_path.exists():
        raise FileNotFoundError(f"Missing data.npz in {run_dir}")
    with np.load(data_path, allow_pickle=False) as data:
        return {k: data[k] for k in data.files}


def _values_close(a: Any, b: Any, *, atol: float = 1e-12) -> bool:
    """Check if two values are close (for float comparison in meta matching)."""
    if isinstance(a, (int, str, bool)) or a is None:
        return a == b
    if isinstance(a, float) or isinstance(b, float):
        try:
            return abs(float(a) - float(b)) <= atol
        except Exception:
            return a == b
    return a == b


def _meta_matches_query(meta: Any, query: Any) -> bool:
    """Return True if `query` is a subset of `meta` (recursive for dicts)."""
    if isinstance(query, Mapping):
        if not isinstance(meta, Mapping):
            return False
        for k, v in query.items():
            if k not in meta:
                return False
            if not _meta_matches_query(meta[k], v):
                return False
        return True
    if isinstance(query, list):
        return meta == query
    return _values_close(meta, query)


def _pick_latest_run(run_dirs: List[Path]) -> Path:
    """Pick the most recently updated run from a list of candidates."""
    def key(p: Path) -> Tuple[str, str]:
        try:
            m = _load_meta(p)
            return (str(m.get("updated_at", "")), str(m.get("created_at", "")))
        except Exception:
            return ("", "")
    return max(run_dirs, key=key)


def _find_run_dir(
    *,
    results_root: Path,
    artifact: str,
    schema_version: int,
    run_hash: Optional[str] = None,
    meta_query: Optional[Dict[str, Any]] = None,
) -> Path:
    """Find a run directory by hash or by matching meta.json fields."""
    if run_hash is not None:
        run_dir = results_root / artifact / f"v{schema_version}" / run_hash
        if not run_dir.exists():
            raise FileNotFoundError(f"No run dir: {run_dir}")
        return run_dir

    if meta_query is None:
        raise ValueError("Provide either run_hash or meta_query")

    candidates: List[Path] = []
    for run_dir in _iter_run_dirs(results_root, artifact, schema_version):
        try:
            meta = _load_meta(run_dir)
        except Exception:
            continue
        if _meta_matches_query(meta, meta_query):
            candidates.append(run_dir)

    if len(candidates) == 0:
        base = results_root / artifact / f"v{schema_version}"
        raise FileNotFoundError(
            f"No matching run found under {base}. "
            f"Generate the data with the scripts first."
        )
    if len(candidates) == 1:
        return candidates[0]
    return _pick_latest_run(candidates)


