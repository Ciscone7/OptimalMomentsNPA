"""Plotting utilities for spin-chain SDP relaxation results.

This module provides functions to visualize results from saved artifacts
(generated by scripts in spins_sdp/scripts/) without recomputing anything.

Main plotting functions:
  - plot_exact_vs_lb: Compare exact ground energy vs moment-relaxation lower bound
  - plot_heisenberg_exact_vs_lb: Heisenberg chain comparison (paper Case B style)
  - plot_heisenberg_j2_sweep: Heisenberg-J2 chain sweep over J2 values (paper Case C style)
  - plot_runtime_comparison: Compare solve times across methods/levels

Utility functions:
  - npa_basis_size_heatmap: Visualize NPA basis size vs N and level
  - plot_basis_size_comparison: Compare basis sizes across methods
"""

